  invoice_date date,
  amount       numeric not null default 0,
  lines        jsonb not null default '[]'::jsonb,
  image        text,
  notes        text
);

-- 5) المستندات الرسمية (خطابات / عروض أسعار / مطالبات مالية)
-- doc_number: رقم الخطاب (تسلسلي سنوي)، attachments: المرفقات، signer_role: منصب صاحب الصلاحية،
