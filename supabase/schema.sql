-- =============== دوال العملاء العامة (SECURITY DEFINER) ===============

-- توليد كود استلام فريد من 5 أرقام (يُستخدم داخليًا فقط).
create or replace function public.generate_pickup_code()
returns text
language plpgsql security definer set search_path = public as $$
declare code text; tries int := 0;
begin
  loop
    code := (floor(random() * 90000) + 10000)::int::text;
    exit when not exists (select 1 from public.orders where pickup_code = code);
    tries := tries + 1;
    exit when tries >= 100; -- في حال امتلاء الأكواد نادرًا نعيد آخر كود مولّد
  end loop;
  return code;
end $$;


-- إنشاء طلب جديد (ينفّذه العملاء بدون تسجيل دخول) ويعيد الطلب المُنشأ.
-- يُولَّد كود الاستلام تلقائيًا إذا كان الطلب مدفوعًا إلكترونيًا (مدى/Apple Pay/فيزا/تابي/تمارا).
create or replace function public.create_order(payload jsonb)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare
  created public.orders;
  pay     jsonb := coalesce(payload->'payment', '{}'::jsonb);
  method  text := coalesce(pay->>'method', '');
  paid    boolean := coalesce(pay->>'status', '') = 'paid';
begin
  insert into public.orders (
    type, table_label, zone_id, zone_name, address, pickup_from, customer_name, phone,
    scheduled_at, guests, notes, lines, subtotal, delivery_fee, total, vat, is_booking,
    priority, payment, status, history, pickup_code
  ) values (
    payload->>'type',
    payload->>'table_label',
    payload->>'zone_id',
    payload->>'zone_name',
    payload->>'address',
    payload->>'pickup_from',
    payload->>'customer_name',
    payload->>'phone',
    (payload->>'scheduled_at')::timestamptz,
    (payload->>'guests')::int,
    payload->>'notes',
    coalesce(payload->'lines', '[]'::jsonb),
    coalesce((payload->>'subtotal')::numeric, 0),
    coalesce((payload->>'delivery_fee')::numeric, 0),
    coalesce((payload->>'total')::numeric, 0),
    coalesce((payload->>'vat')::numeric, 0),
    coalesce((payload->>'is_booking')::boolean, false),
    coalesce(payload->>'priority', 'normal'),
    pay,
    coalesce(payload->>'status', 'new'),
    coalesce(payload->'history', '[]'::jsonb),
    case
      when paid and method in ('mada', 'applepay', 'visa', 'tabby', 'tamara', 'bank')
        then public.generate_pickup_code()
      else null
    end
  )
  returning * into created;
  return created;
end $$;

-- تأكيد دفع طلب (الشبكة عند الاستلام أو التحويل البنكي) وتوليد كود الاستلام الأمني.
-- متاحة للموظفين المسجّلين فقط (owner / kitchen / staff).
create or replace function public.confirm_order_payment(p_id uuid)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare
  updated public.orders;
  method  text;
begin
  if not public.has_staff_role('owner', 'kitchen', 'staff') then
    raise exception 'لا تملك صلاحية تأكيد الدفع';
  end if;

  select * into updated from public.orders where id = p_id;
  if not found then
    return null;
  end if;

  method := coalesce(updated.payment->>'method', '');

  update public.orders
    set payment = jsonb_set(coalesce(payment, '{}'::jsonb), '{status}', '"paid"'::jsonb),
        pickup_code = case
          when pickup_code is not null then pickup_code
          when method in ('mada', 'applepay', 'visa', 'tabby', 'tamara', 'bank') then public.generate_pickup_code()
          else null
        end
    where id = p_id
    returning * into updated;

  return updated;
end $$;


-- إرسال شكوى جديدة من عميل بدون تسجيل دخول.
create or replace function public.create_complaint(
  p_name text,
  p_phone text,
  p_message text,
  p_order_number text default ''
)
returns public.complaints
language plpgsql security definer set search_path = public as $$
declare created public.complaints;
begin
  insert into public.complaints (name, phone, message, order_number, reply, status)
  values (p_name, p_phone, p_message, nullif(p_order_number, ''), '', 'open')
  returning * into created;
  return created;
end $$;

-- تتبّع طلب برقم الطلب + آخر 9 أرقام من الجوال.
create or replace function public.track_order(p_number bigint, p_phone text)
returns setof public.orders
language sql security definer set search_path = public as $$
  select *
  from public.orders
  where number = p_number
    and right(regexp_replace(coalesce(phone, ''), '\D', '', 'g'), 9)
      = right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 9)
  limit 1;
$$;

-- قراءة طلب واحد بمعرّفه (لفتح صفحة الفاتورة/البون من رابط العميل).
create or replace function public.get_order(p_id uuid)
returns public.orders
language sql security definer set search_path = public as $$
  select * from public.orders where id = p_id limit 1;
$$;

-- شكاوى عميل معيّن حسب آخر 9 أرقام من جواله.
create or replace function public.track_complaints(p_phone text)
returns setof public.complaints
language sql security definer set search_path = public as $$
  select *
  from public.complaints
  where right(regexp_replace(coalesce(phone, ''), '\D', '', 'g'), 9)
      = right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 9)
  order by created_at desc;
$$;

-- خصم الكميات من المخزون بعد نجاح الطلب (بدون منح anon صلاحية تعديل الأصناف).
create or replace function public.decrement_menu_stock(p_items jsonb)
returns void
language plpgsql security definer set search_path = public as $$
declare item jsonb;
begin
  for item in select * from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) loop
    update public.menu_items
      set stock = greatest(0, stock - coalesce((item->>'qty')::int, 0))
      where id = (item->>'itemId')::uuid
        and stock is not null;
  end loop;
end $$;

