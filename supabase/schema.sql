-- مخطط قاعدة بيانات Supabase لمشروع «مطاعم ومطابخ وادي دوعن» (جدة)
-- نفّذ هذا الملف في Supabase SQL Editor.
--
-- ملاحظة مهمة عن الأمان:
-- التطبيق يستخدم المفتاح العام NEXT_PUBLIC_SUPABASE_ANON_KEY في الواجهة والخادم،
-- لذلك فعّلنا RLS على كل الجداول. عمليات العملاء العامة (إنشاء طلب، إرسال شكوى،
-- تتبّع الطلب، خصم الكميات) تمر عبر دوال SECURITY DEFINER بدل منح anon صلاحيات
-- قراءة/كتابة مباشرة على الجداول، حتى لا يمكن لأي شخص قراءة بيانات العملاء.
--
-- أنشئ حسابات الموظفين من: Authentication > Users > Add user (بريد + كلمة مرور)،
-- ثم عيّن دور كل حساب في User Metadata باسم role (انظر قسم الأدوار أدناه).

-- 1) الإعدادات (الهوية البصرية + الأحياء + الحسابات البنكية)
create table if not exists public.settings (
