-- =============== الترقيم الإلكتروني السنوي للخطابات ===============

-- يحجز ويعيد رقم الخطاب التالي بصيغة السنة/التسلسل (مثال: 2026/001)، ويتصفّر تلقائيًا مع كل سنة جديدة.
create or replace function public.next_document_number(p_year integer default null)
returns text
language plpgsql security definer set search_path = public as $$
declare
  yr integer;
  n  integer;
begin
  yr := coalesce(p_year, extract(year from now())::int);
  insert into public.document_counters (year, last_number)
  values (yr, 1)
  on conflict (year) do update set last_number = public.document_counters.last_number + 1
  returning last_number into n;
  return yr::text || '/' || lpad(n::text, 3, '0');
end $$;

-- يعيد رقم الخطاب التالي المتوقع دون حجزه (لعرضه في المعاينة قبل الحفظ).
create or replace function public.peek_document_number(p_year integer default null)
returns text
language plpgsql stable security definer set search_path = public as $$
declare
  yr integer;
  n  integer;
begin
  yr := coalesce(p_year, extract(year from now())::int);
  select coalesce(max(last_number), 0) + 1 into n from public.document_counters where year = yr;
  return yr::text || '/' || lpad(n::text, 3, '0');
end $$;

grant execute on function public.next_document_number(integer) to authenticated;
grant execute on function public.peek_document_number(integer) to authenticated;

-- =============== دوال العملاء العامة (SECURITY DEFINER) ===============

-- توليد كود استلام فريد من 4 أرقام (1000 - 9999) يُستخدم داخليًا فقط.
create or replace function public.generate_pickup_code()
returns text
language plpgsql security definer set search_path = public as $$
declare code text; tries int := 0;
begin
  loop
    code := (floor(random() * 9000) + 1000)::int::text;
    exit when not exists (select 1 from public.orders where pickup_code = code);
    tries := tries + 1;
    exit when tries >= 100; -- في حال امتلاء الأكواد نادرًا نعيد آخر كود مولّد
  end loop;
  return code;
end $$;


-- إنشاء طلب جديد (ينفّذه العملاء بدون تسجيل دخول) ويعيد الطلب المُنشأ.
-- يُولَّد كود الاستلام (4 أرقام) فور تأكيد الطلب الإلكتروني مباشرة (كل الأنواع عدا الطلب المحلي).
create or replace function public.create_order(payload jsonb)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare
  created public.orders;
  pay     jsonb := coalesce(payload->'payment', '{}'::jsonb);
  is_local boolean := coalesce(payload->>'type', '') = 'dinein';
begin
  insert into public.orders (
    type, table_label, zone_id, zone_name, address, short_address, lat, lng, pickup_from, customer_name, phone,
    scheduled_at, guests, notes, lines, subtotal, delivery_fee, total, vat, is_booking,
    priority, payment, status, history, pickup_code
  ) values (
    payload->>'type',
    payload->>'table_label',
    payload->>'zone_id',
    payload->>'zone_name',
    payload->>'address',
    payload->>'short_address',
    (payload->>'lat')::numeric,
    (payload->>'lng')::numeric,
    payload->>'pickup_from',
    payload->>'customer_name',
    payload->>'phone',
    (payload->>'scheduled_at')::timestamptz,
    (payload->>'guests')::int,
    payload->>'notes',
    coalesce(payload->'lines', '[]'::jsonb),
    coalesce((payload->>'subtotal')::numeric, 0),
    coalesce((payload->>'delivery_fee')::numeric, 0),
    coalesce((payload->>'total')::numeric, 0),
    coalesce((payload->>'vat')::numeric, 0),
    coalesce((payload->>'is_booking')::boolean, false),
    coalesce(payload->>'priority', 'normal'),
    pay,
    coalesce(payload->>'status', 'new'),
    coalesce(payload->'history', '[]'::jsonb),
    case
      when is_local then null
      else public.generate_pickup_code()
    end
  )
  returning * into created;
  return created;
end $$;

-- تأكيد دفع طلب وتوليد كود الاستلام عند غيابه (احتياطًا للطلبات الإلكترونية القديمة).
-- متاحة للموظفين المسجّلين فقط (owner / kitchen / staff).
create or replace function public.confirm_order_payment(p_id uuid)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare
  updated public.orders;
begin
  if not public.has_staff_role('owner', 'kitchen', 'kitchen_manager', 'kitchen_supervisor', 'staff', 'restaurant_manager', 'restaurant_supervisor') then
    raise exception 'لا تملك صلاحية تأكيد الدفع';
  end if;

  select * into updated from public.orders where id = p_id;
  if not found then
    return null;
  end if;

  update public.orders
    set payment = jsonb_set(coalesce(payment, '{}'::jsonb), '{status}', '"paid"'::jsonb),
        pickup_code = case
          when pickup_code is not null then pickup_code
          when coalesce(type, '') = 'dinein' then null
          else public.generate_pickup_code()
        end
    where id = p_id
    returning * into updated;

  return updated;
end $$;


-- إرسال شكوى أو اقتراح من عميل بدون تسجيل دخول (النوع إلزامي: complaint / suggestion).
create or replace function public.create_complaint(
  p_name text,
  p_phone text,
  p_message text,
  p_order_number text default '',
  p_type text default 'complaint'
)
returns public.complaints
language plpgsql security definer set search_path = public as $$
declare created public.complaints;
begin
  insert into public.complaints (name, phone, message, order_number, type, reply, status)
  values (
    p_name,
    p_phone,
    p_message,
    nullif(p_order_number, ''),
    case when p_type = 'suggestion' then 'suggestion' else 'complaint' end,
    '',
    'open'
  )
  returning * into created;
  return created;
end $$;

-- تتبّع طلب برقم الطلب + آخر 9 أرقام من الجوال.
create or replace function public.track_order(p_number bigint, p_phone text)
returns setof public.orders
language sql security definer set search_path = public as $$
  select *
  from public.orders
  where number = p_number
    and right(regexp_replace(coalesce(phone, ''), '\D', '', 'g'), 9)
      = right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 9)
  limit 1;
$$;

-- قراءة طلب واحد بمعرّفه (لفتح صفحة الفاتورة/البون من رابط العميل).
create or replace function public.get_order(p_id uuid)
returns public.orders
language sql security definer set search_path = public as $$
  select * from public.orders where id = p_id limit 1;
$$;

-- شكاوى عميل معيّن حسب آخر 9 أرقام من جواله.
create or replace function public.track_complaints(p_phone text)
returns setof public.complaints
language sql security definer set search_path = public as $$
  select *
  from public.complaints
  where right(regexp_replace(coalesce(phone, ''), '\D', '', 'g'), 9)
      = right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 9)
  order by created_at desc;
$$;

-- خصم الكميات من المخزون بعد نجاح الطلب (بدون منح anon صلاحية تعديل الأصناف).
create or replace function public.decrement_menu_stock(p_items jsonb)
returns void
language plpgsql security definer set search_path = public as $$
declare item jsonb;
begin
  for item in select * from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) loop
    update public.menu_items
      set stock = greatest(0, stock - coalesce((item->>'qty')::int, 0))
      where id = (item->>'itemId')::uuid
        and stock is not null;
  end loop;
end $$;

-- تحديث حالة طلب إلى «جاهز للتسليم» (يُستدعى بمسح باركود بون المطبخ من جوال الطاقم بدون تسجيل دخول).
create or replace function public.mark_order_ready(p_id uuid)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare updated public.orders;
begin
  update public.orders
    set status = 'ready',
        history = coalesce(history, '[]'::jsonb) || jsonb_build_object('status', 'ready', 'at', now())
    where id = p_id
      and status in ('new', 'preparing')
    returning * into updated;

  if updated.id is null then
    select * into updated from public.orders where id = p_id;
  end if;
  return updated;
end $$;

-- إتمام الدفع الإلكتروني لطلب الطاولة: يحوّل الدفع إلى «مدفوع» ويغلق الطاولة ويجعلها متاحة.
create or replace function public.pay_table_order(p_id uuid, p_table text)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare updated public.orders;
begin
  update public.orders
    set payment = jsonb_set(coalesce(payment, '{}'::jsonb), '{status}', '"paid"'::jsonb)
    where id = p_id
    returning * into updated;

  if p_table is not null and btrim(p_table) <> '' then
    insert into public.restaurant_tables (table_no, status, updated_at)
    values (btrim(p_table)::int, 'closed', now())
    on conflict (table_no) do update set status = 'closed', updated_at = now();
  end if;

  return updated;
end $$;

-- تحديث حالة طاولة (open مشغولة / closed متاحة).
create or replace function public.set_table_status(p_no integer, p_status text)
returns void
language plpgsql security definer set search_path = public as $$
begin
  insert into public.restaurant_tables (table_no, status, updated_at)
  values (p_no, case when p_status = 'closed' then 'closed' else 'open' end, now())
  on conflict (table_no) do update set status = excluded.status, updated_at = now();
end $$;

-- حفظ تقييم خدمة من العميل بعد الدفع (بدون تسجيل دخول).
create or replace function public.create_rating(
  p_order_id uuid,
  p_table text,
  p_rating integer,
  p_comment text default '',
  p_customer text default ''
)
returns void
language plpgsql security definer set search_path = public as $$
begin
  insert into public.service_ratings (order_id, table_no, rating, comment, customer)
  values (
    p_order_id,
    nullif(btrim(coalesce(p_table, '')), ''),
    least(5, greatest(1, coalesce(p_rating, 5))),
    left(coalesce(p_comment, ''), 1000),
    nullif(btrim(coalesce(p_customer, '')), '')
  );
end $$;

