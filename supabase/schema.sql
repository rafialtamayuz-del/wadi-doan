-- ================== أدوار الموظفين (RBAC) ==================
-- يُقرأ دور المستخدم من User Metadata باسم role بأحد القيم: owner / kitchen / staff.
--   owner   = صاحب المشروع (كل الصلاحيات)
--   kitchen = موظف المطبخ (شاشة التحضير KDS وتحديث حالات الطلبات)
--   staff   = موظف المطعم (إدارة الطلبات والكاشير وطباعة الفواتير)
-- الحسابات التي لا يحتوي metadata على role تُعامل «صاحب المشروع» (توافقًا مع الحسابات السابقة).
--
-- لتعيين الدور من لوحة Supabase: Authentication > Users > اختر المستخدم > User Metadata:
--   { "role": "kitchen" }
-- أو عبر SQL:
--   update auth.users
--   set raw_user_meta_data = coalesce(raw_user_meta_data, '{}'::jsonb) || jsonb_build_object('role', 'kitchen')
--   where email = 'kitchen@example.com';

create or replace function public.current_staff_role()
returns text
language sql stable
set search_path = public as $$
  select coalesce(auth.jwt() -> 'user_metadata' ->> 'role', 'owner')
$$;

-- هل دور المستخدم الحالي ضمن الأدوار الممرَّرة؟
create or replace function public.has_staff_role(variadic p_roles text[])
returns boolean
language sql stable
set search_path = public as $$
  select public.current_staff_role() = any (p_roles)
$$;

grant execute on function public.current_staff_role() to anon, authenticated;
grant execute on function public.has_staff_role(text[]) to anon, authenticated;

